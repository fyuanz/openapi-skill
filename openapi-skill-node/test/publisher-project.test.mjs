test('removes a stale service when the complete project tree is replaced', async () => {
  const output = await mkdtemp(join(tmpdir(), 'openapi-skill-publish-removal-'));
  const complete = generateProjectSkill({ services: [
    { serviceId: 'orders', documents: new Map([['public', bytes]]) },
    { serviceId: 'shipping', documents: new Map([['public', bytes]]) }
  ] });
  const directory = await publishSkill(output, 'api-docs', 'api-docs', complete);
  const reduced = generateProjectSkill({ services: [{ serviceId: 'orders', documents: new Map([['public', bytes]]) }] });
  await publishSkill(output, 'api-docs', 'api-docs', reduced);
  const source = JSON.parse(await readFile(join(directory, 'references', 'source.json'), 'utf8'));
  assert.deepEqual(source.services.map(({ serviceId }) => serviceId), ['orders']);
  await assert.rejects(readFile(join(directory, 'references', 'services', 'shipping', 'references', 'source.json'), 'utf8'), /ENOENT/);
});

test('rejects inconsistent project provenance before writing output', async () => {
  const output = await mkdtemp(join(tmpdir(), 'openapi-skill-publish-invalid-project-'));
  const project = new Map(generateProjectSkill({ services: [
    { serviceId: 'orders', documents: new Map([['public', bytes]]) }
  ] }));
  const source = JSON.parse(project.get('references/source.json'));
  source.documents = [];
  project.set('references/source.json', JSON.stringify(source, null, 2));
  await assert.rejects(publishSkill(output, 'api-docs', 'api-docs', project), /flattened project documents/);
});

test('rejects an openapi-skill core/3 index that points to a missing contract', async () => {
  const output = await mkdtemp(join(tmpdir(), 'openapi-skill-publish-invalid-index-'));
  const operation = new TextEncoder().encode('{"openapi":"3.1.0","paths":{"/x":{"get":{"responses":{}}}}}');
  const files = new Map(generateSkill({
    serviceId: 'orders', skillName: 'orders-api', documents: new Map([['public', operation]])
  }));
  files.set('references/operations.jsonl', files.get('references/operations.jsonl')
    .replace('documents/public/operations/', 'documents/public/missing/'));
  await assert.rejects(publishSkill(output, 'orders', 'orders-api', files), /missing contract file/);
});
