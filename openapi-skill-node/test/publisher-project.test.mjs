import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { generateProjectSkill, generateSkill, publishSkill } from '../dist/index.js';

const bytes = new TextEncoder().encode('{"openapi":"3.1.0","paths":{}}');

test('atomically migrates the same output between legacy and project generated trees', async () => {
  const output = await mkdtemp(join(tmpdir(), 'openapi-skill-publish-project-'));
  const legacy = generateSkill({ serviceId: 'legacy', skillName: 'api-docs', documents: new Map([['public', bytes]]) });
  const directory = await publishSkill(output, 'legacy', 'api-docs', legacy);
  assert.equal(JSON.parse(await readFile(join(directory, 'references', 'source.json'), 'utf8')).serviceId, 'legacy');

  const project = generateProjectSkill({ services: [
    { serviceId: 'orders', documents: new Map([['public', bytes]]) },
    { serviceId: 'shipping', sourceType: 'third-party', documents: new Map([['public', bytes]]) }
  ] });
  await publishSkill(output, 'api-docs', 'api-docs', project);
  assert.equal(JSON.parse(await readFile(join(directory, 'references', 'source.json'), 'utf8')).kind, 'project');

  await publishSkill(output, 'legacy', 'api-docs', legacy);
  assert.equal(JSON.parse(await readFile(join(directory, 'references', 'source.json'), 'utf8')).serviceId, 'legacy');
});

test('safely replaces an owned project generated by the former package identity', async () => {
  const output = await mkdtemp(join(tmpdir(), 'openapi-skill-publish-former-name-'));
  const previous = generateProjectSkill({ services: [
    { serviceId: 'orders', documents: new Map([['public', bytes]]) }
  ] });
  for (const [path, content] of previous) {
    const target = join(output, 'api-docs', ...path.split('/'));
    await mkdir(join(target, '..'), { recursive: true });
    await writeFile(target, content.replaceAll('openapi-skill-core/3', 'smartdoc-agent-core/3'));
  }

  const next = generateProjectSkill({ services: [
    { serviceId: 'orders', documents: new Map([['public', bytes]]) },
    { serviceId: 'shipping', documents: new Map([['public', bytes]]) }
  ] });
  const directory = await publishSkill(output, 'api-docs', 'api-docs', next);
  const source = JSON.parse(await readFile(join(directory, 'references', 'source.json'), 'utf8'));
  assert.equal(source.generatorVersion, 'openapi-skill-core/3');
  assert.deepEqual(source.services.map(({ serviceId }) => serviceId), ['orders', 'shipping']);
});

